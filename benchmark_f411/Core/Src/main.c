/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  /* MX_USB_OTG_FS_PCD_Init() is deliberately NOT called -- TinyUSB drives the
   * OTG_FS registers directly and HAL_PCD_Init() would reconfigure the same
   * core underneath it. See usb/usb_glue.c. */
  /* USER CODE BEGIN 2 */

  /* Run the throughput probe once, at boot, before anything else can compete
   * for the core. Results land in g_bench -- read it with the debugger
   * ("print g_bench", or dump the struct) and over SWO/ITM if trace is up. */
#ifdef BENCH_WITH_PROBE
  bench_run_all();
#else
  /* Deployed streaming image: no probe, but the cycle counter must run for
   * the ABF1 tick source. g_bench.done drives the heartbeat only. */
  g_bench.cpu_hz = SystemCoreClock;
  g_bench.done   = bench_dwt_init() ? 1u : 0u;
#endif

  /* USB comes up only AFTER the probe has finished. The probe masks interrupts
   * around every timed region, and an enumeration storm arriving mid-suite
   * would be exactly the kind of I/O-inside-a-measurement the harness design
   * rules forbid. Order matters here; do not move this above bench_run_all(). */
#ifdef BENCH_WITH_TINYUSB
  usb_glue_abf_init();   /* image CRC + HELLO identity + binding, before enumeration */
  usb_glue_init();
#endif

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
#ifdef BENCH_WITH_TINYUSB
    tud_task();
    abf_cdc_service();   /* task 7's framing; never blocks, one packet per call */
#endif

    /* Heartbeat: slow blink means the suite completed, fast means it did not
     * (DWT never started). PC13 is active-low on this board. Non-blocking now
     * -- HAL_Delay() here would stall tud_task() for half a second at a time
     * and the device would fail to enumerate. */
    {
      static uint32_t last = 0u;
      const uint32_t period = g_bench.done ? 500u : 100u;
      const uint32_t now = HAL_GetTick();
      if ((now - last) >= period) {
        last = now;
        HAL_GPIO_TogglePin(GPIOC, GPIO_PIN_13);
      }
    }
  }
  /* USER CODE END 3 */
}

/**
  * @brief System Clock Configuration
  * @retval None
  */
void SystemClock_Config(void)
{
  RCC_OscInitTypeDef RCC_OscInitStruct = {0};
  RCC_ClkInitTypeDef RCC_ClkInitStruct = {0};

  /** Configure the main internal regulator output voltage
  */
  __HAL_RCC_PWR_CLK_ENABLE();
  __HAL_PWR_VOLTAGESCALING_CONFIG(PWR_REGULATOR_VOLTAGE_SCALE1);

  /** Initializes the RCC Oscillators according to the specified parameters
  * in the RCC_OscInitTypeDef structure.
  */
  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_HSE;
  RCC_OscInitStruct.HSEState = RCC_HSE_ON;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLLSOURCE_HSE;
  RCC_OscInitStruct.PLL.PLLM = 25;
  RCC_OscInitStruct.PLL.PLLN = 384;
  RCC_OscInitStruct.PLL.PLLP = RCC_PLLP_DIV4;
  RCC_OscInitStruct.PLL.PLLQ = 8;
  if (HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    Error_Handler();
  }

  /** Initializes the CPU, AHB and APB buses clocks
  */
  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1|RCC_CLOCKTYPE_PCLK2;
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV2;
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV1;

  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_3) != HAL_OK)
  {
    Error_Handler();
  }
  HAL_RCC_MCOConfig(RCC_MCO1, RCC_MCO1SOURCE_PLLCLK, RCC_MCODIV_4);

  /** Enables the Clock Security System
  */
  HAL_RCC_EnableCSS();
}

