#!/usr/bin/env python3
"""Emit a DTLN TFLite pair as C arrays for the MCU ports, with provenance.

    python3 dtln/port/gen_model_c.py RUN_DIR/shrunk OUT.c [--tag i16]

Writes OUT.c defining `dtln_model_1[]`, `dtln_model_1_len`, `dtln_model_2[]`,
`dtln_model_2_len` (16-byte aligned, const -> .rodata, i.e. flash), and a
header comment carrying each file's byte count and SHA-256 so the image's
provenance is checkable against the artifact that was scored on the host.
The arrays are what TFLite Micro's GetModel() reads; nothing is transformed.

`--align-inplace` (2026-10-22, for the S3 PIE kernel): a flatbuffer only
guarantees 4-byte alignment of its vectors, and the 128-bit PIE loads need
the weight rows of the big FC / 1x1-conv tensors (depth a multiple of 16)
16-byte aligned WHERE THEY SIT, so they can be read in place from flash or
PSRAM instead of copied. Each weight buffer's file offset is read out of the
flatbuffer; if every such tensor shares one offset mod 16 the array is
emitted with that many leading zero bytes and `dtln_model_k_pad` names the
count, so `dtln_model_k + dtln_model_k_pad` is the flatbuffer and every
in-place tensor lands on a 16-byte boundary. Not one byte of the flatbuffer
changes (the SHA-256 in the header is of the file, and the array after the
pad is byte-identical to it); the pad is 4-aligned, so every other vector
keeps the 4-byte alignment the flatbuffer promised. If the tensors disagree
mod 16 the generator refuses rather than aligning some of them.
"""
import argparse, hashlib, sys
from pathlib import Path


def inplace_pad(blob, label):
    """Leading pad (0..12, multiple of 4) that 16-aligns every in-place weight tensor."""
    from tflite.Model import Model
    from tflite.BuiltinOperator import BuiltinOperator as B
    import flatbuffers
    m = Model.GetRootAsModel(blob, 0)
    sg = m.Subgraphs(0)
    sites = []
    for i in range(sg.OperatorsLength()):
        op = sg.Operators(i); oc = m.OperatorCodes(op.OpcodeIndex())
        code = oc.BuiltinCode() if oc.BuiltinCode() != 0 else oc.DeprecatedBuiltinCode()
        if code not in (B.FULLY_CONNECTED, B.CONV_2D) or op.InputsLength() < 2 or op.Inputs(1) < 0:
            continue
        t = sg.Tensors(op.Inputs(1))
        if t.Type() != 9:                       # INT8 filter only
            continue
        dims = [t.Shape(k) for k in range(t.ShapeLength())]
        depth = dims[-1]
        if depth % 16 != 0:                     # the glue copies these into its padded pool
            continue
        buf = m.Buffers(t.Buffer())
        o = flatbuffers.number_types.UOffsetTFlags.py_type(buf._tab.Offset(4))
        if o == 0:
            continue
        start = buf._tab.Vector(o)
        sites.append((t.Name().decode(), dims, start, start % 16))
    if not sites:
        return 0, sites
    mods = {s[3] for s in sites}
    if len(mods) != 1:
        raise SystemExit(f"{label}: in-place weight tensors disagree mod 16: " +
                         "; ".join(f"{n} @{st} (mod {md})" for n, _, st, md in sites))
    return (16 - mods.pop()) % 16, sites


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("model_dir", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--tag", default="i16", help="file tag: model_<tag>_{1,2}.tflite")
    ap.add_argument("--align-inplace", action="store_true",
                    help="lead each array with the pad that 16-aligns its in-place weight rows; emits dtln_model_k_pad")
    a = ap.parse_args(argv)
    files = [a.model_dir / f"model_{a.tag}_{k}.tflite" for k in (1, 2)]
    out = [f"/* GENERATED by dtln/port/gen_model_c.py -- do not edit.\n *\n"
           f" * Source: {a.model_dir}\n"]
    bodies = []
    for k, f in enumerate(files, 1):
        b = f.read_bytes()
        out.append(f" *   {f.name}: {len(b):,} B  sha256 {hashlib.sha256(b).hexdigest()}\n")
        pad, sites = (inplace_pad(b, f.name) if a.align_inplace else (0, []))
        for n, dims, st, md in sites:
            out.append(f" *     in-place weight {n} {dims}: file offset {st} (mod 16 = {md})"
                       f" -> array offset {st + pad} (mod 16 = {(st + pad) % 16})\n")
        if a.align_inplace:
            out.append(f" *   --align-inplace: dtln_model_{k} leads with {pad} zero bytes; "
                       f"dtln_model_{k} + dtln_model_{k}_pad is the flatbuffer\n")
        bodies.append((k, b, pad))
    out.append(" */\n#include <stddef.h>\n#include <stdint.h>\n\n")
    for k, b, pad in bodies:
        pb = bytes(pad) + b
        out.append(f"__attribute__((aligned(16))) const uint8_t dtln_model_{k}[{len(pb)}] = {{\n")
        for i in range(0, len(pb), 16):
            out.append("  " + ",".join(f"0x{x:02x}" for x in pb[i:i + 16]) + ",\n")
        out.append(f"}};\nconst size_t dtln_model_{k}_len = {len(b)};\n")
        if a.align_inplace:
            out.append(f"const size_t dtln_model_{k}_pad = {pad};\n")
        out.append("\n")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("".join(out))
    print(f"{a.out}: {sum(len(b) for _, b, _ in bodies):,} B of model in two arrays"
          + (", pads " + "/".join(str(p) for _, _, p in bodies) if a.align_inplace else ""))


if __name__ == "__main__":
    sys.exit(main())
