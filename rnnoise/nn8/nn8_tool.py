#!/usr/bin/env python3
"""nn8_tool.py -- generate and verify the "+N" RNNoise variant's derived sources.

The +N variant runs Xiph RNNoise's three GRUs on CMSIS-NN's s8 vector-by-matrix
kernel (arm_nn_vec_mat_mult_t_svdf_s8, V.6.2.0) instead of the shipped scalar
float loop. The weights are the shipped 8-bit ones, unchanged in value; only
their layout changes, because the shipped loop reads them transposed
(input_weights[j*3N + i] for output i, input j) and the kernel wants one
contiguous row per output. Nothing else about the model moves.

Two derived files are written by `gen` and re-verified by `check` at every
configure (host and F411 alike), so neither can drift from the vendored tree:

  rnn_nn8_weights.c  the transposed GRU matrices, gate-major rows
                     (z: rows 0..N-1, r: N..2N-1, h: 2N..3N-1), one row per
                     output of length M (input weights) or N (recurrent).
                     Same bytes as rnn_data.c, permuted; asserted here by
                     inverting the permutation.
  rnn_nn8.c          the vendored rnn.c with compute_gru's body replaced by a
                     one-line forwarder to rnnoise_nn8_compute_gru() and one
                     #include added. `check` rebuilds it from rnn.c and
                     requires byte equality, so it cannot carry any other edit.

`check` also requires that tansig_approx, sigmoid_approx and relu in
rnn_nn8_gru.c are verbatim copies of rnn.c's (they are static there), so the
activations the variant applies are the shipped ones.
"""
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "xiph-v0.1.1" / "src"
RNN_C = SRC / "rnn.c"
RNN_DATA_C = SRC / "rnn_data.c"
OUT_W = HERE / "rnn_nn8_weights.c"
OUT_RNN = HERE / "rnn_nn8.c"
GRU_C = HERE / "rnn_nn8_gru.c"

FORWARDER = """static void compute_gru(const GRULayer *gru, float *state, const float *input)
{
   rnnoise_nn8_compute_gru(gru, state, input);   /* +N: CMSIS-NN GRU, rnn_nn8_gru.c */
}
"""


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def parse_rnn_data(text: str):
    arrays = {}
    for m in re.finditer(r"static const rnn_weight (\w+)\[(\d+)\] = \{(.*?)\};", text, re.S):
        name, n, body = m.group(1), int(m.group(2)), m.group(3)
        vals = [int(v) for v in re.findall(r"-?\d+", body)]
        assert len(vals) == n, f"{name}: {len(vals)} values, declared {n}"
        assert all(-128 <= v <= 127 for v in vals), name
        arrays[name] = vals
    grus = []
    for m in re.finditer(r"static const GRULayer (\w+) = \{\s*(\w+),\s*(\w+),\s*(\w+),\s*(\d+), (\d+), (\w+)\s*\};", text):
        name, bias, w_in, w_rec, M, N, act = m.groups()
        grus.append(dict(name=name, bias=bias, w_in=w_in, w_rec=w_rec, M=int(M), N=int(N), act=act))
    assert [g["name"] for g in grus] == ["vad_gru", "noise_gru", "denoise_gru"], grus
    return arrays, grus


def transpose(w, M, N):
    """shipped: w[g*N + j*3N + i] -> ours: t[(g*N + i)*M + j]  (g gate, i output, j input)."""
    assert len(w) == 3 * N * M
    t = [0] * len(w)
    for g in range(3):
        for i in range(N):
            for j in range(M):
                t[(g * N + i) * M + j] = w[g * N + j * 3 * N + i]
    # invert and compare: the permutation must be a bijection on the same bytes
    back = [0] * len(w)
    for g in range(3):
        for i in range(N):
            for j in range(M):
                back[g * N + j * 3 * N + i] = t[(g * N + i) * M + j]
    assert back == w
    assert sorted(t) == sorted(w)
    return t


def emit_rows(vals, per_line=20):
    lines = []
    for k in range(0, len(vals), per_line):
        lines.append("   " + ", ".join(f"{v}" for v in vals[k:k + per_line]) + ",")
    return "\n".join(lines)


def gen_weights_text() -> str:
    text = RNN_DATA_C.read_text()
    arrays, grus = parse_rnn_data(text)
    out = []
    out.append("/* rnn_nn8_weights.c -- GENERATED by nn8_tool.py from xiph-v0.1.1/src/rnn_data.c")
    out.append(f" * (sha256 {sha256(RNN_DATA_C)}). Do not edit: `nn8_tool.py gen` rewrites it and")
    out.append(" * `nn8_tool.py check` fails the configure if it differs from a fresh generation.")
    out.append(" *")
    out.append(" * The shipped GRU weights, same values, re-laid for arm_nn_vec_mat_mult_t_svdf_s8:")
    out.append(" * one contiguous row per output, gate-major (z rows 0..N-1, r rows N..2N-1,")
    out.append(" * h rows 2N..3N-1). Shipped index g*N + j*3N + i maps to row g*N+i, column j. */")
    out.append('#include "rnn_nn8.h"')
    out.append("")
    for g in grus:
        M, N = g["M"], g["N"]
        t_in = transpose(arrays[g["w_in"]], M, N)
        t_rec = transpose(arrays[g["w_rec"]], N, N)
        out.append(f"/* {g['name']}: {M} inputs, {N} neurons */")
        out.append(f"static const signed char {g['name']}_nn8_in[{3 * N * M}] = {{")
        out.append(emit_rows(t_in))
        out.append("};")
        out.append(f"static const signed char {g['name']}_nn8_rec[{3 * N * N}] = {{")
        out.append(emit_rows(t_rec))
        out.append("};")
        out.append("")
    out.append("const rnnoise_nn8_gru_t rnnoise_nn8_grus[RNNOISE_NN8_GRUS] = {")
    for g in grus:
        out.append(f"   {{ {g['M']}, {g['N']}, {g['name']}_nn8_in, {g['name']}_nn8_rec }},")
    out.append("};")
    out.append("")
    return "\n".join(out)


def gen_rnn_text() -> str:
    text = RNN_C.read_text()
    m = re.search(r"static void compute_gru\(const GRULayer \*gru, float \*state, const float \*input\)\n\{\n.*?\n\}\n",
                  text, re.S)
    assert m, "compute_gru not found in rnn.c"
    text = text[:m.start()] + FORWARDER + text[m.end():]
    inc = '#include "rnn_data.h"\n'
    assert text.count(inc) == 1
    text = text.replace(inc, inc + '#include "rnn_nn8.h"   /* +N: rnnoise_nn8_compute_gru() */\n')
    return text


def extract_fn(text: str, head: str) -> str:
    m = re.search(re.escape(head) + r"\n\{\n.*?\n\}\n", text, re.S)
    assert m, head
    return m.group(0)


def check() -> int:
    bad = 0
    want_w = gen_weights_text()
    if not OUT_W.exists() or OUT_W.read_text() != want_w:
        print(f"nn8 check: {OUT_W.name} differs from a fresh generation (run `nn8_tool.py gen`)")
        bad += 1
    want_r = gen_rnn_text()
    if not OUT_RNN.exists() or OUT_RNN.read_text() != want_r:
        print(f"nn8 check: {OUT_RNN.name} is not rnn.c + forwarder + one #include (run `nn8_tool.py gen`)")
        bad += 1
    rnn = RNN_C.read_text()
    gru = GRU_C.read_text() if GRU_C.exists() else ""
    for head in ("static OPUS_INLINE float tansig_approx(float x)",
                 "static OPUS_INLINE float sigmoid_approx(float x)",
                 "static OPUS_INLINE float relu(float x)"):
        fn = extract_fn(rnn, head)
        if fn not in gru:
            print(f"nn8 check: {GRU_C.name} does not carry rnn.c's {head.split()[-1]} verbatim")
            bad += 1
    if not bad:
        print(f"nn8 check: OK (rnn_data.c sha256 {sha256(RNN_DATA_C)[:16]}..., rnn.c sha256 {sha256(RNN_C)[:16]}...)")
    return 1 if bad else 0


def main(argv):
    if len(argv) != 2 or argv[1] not in ("gen", "check"):
        print(__doc__)
        return 2
    if argv[1] == "gen":
        OUT_W.write_text(gen_weights_text())
        OUT_RNN.write_text(gen_rnn_text())
        print(f"wrote {OUT_W} and {OUT_RNN}")
        return 0
    return check()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
